// Product documentation pipeline. Products and paths are configured in scripts/docs.config.json.
//
//   node scripts/docs.mjs import [product] [--source <folder>]   copy the Markdown and images verbatim into docs-src/
//   node scripts/docs.mjs build  [product]                       render docs-src/ into the product's docs folder
//   node scripts/docs.mjs check  [product]                       verify links, code blocks and that the output is current
//
// The Markdown is never edited: links between .md files become links between .html pages, and
// headings get the same IDs GitHub gives them, so the docs' existing anchors keep working.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import hljs from './vendor/highlight/core.min.js';
import csharp from './vendor/highlight/csharp.min.js';
import { Marked, Renderer } from './vendor/marked.esm.js';

hljs.registerLanguage('csharp', csharp);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG = JSON.parse(await readFile(path.join(ROOT, 'scripts/docs.config.json'), 'utf8'));
const TEMPLATE = await readFile(path.join(ROOT, 'scripts/docs-template.html'), 'utf8');
const MARKER = 'Generated by scripts/docs.mjs';
const MANIFEST = 'IMPORT.json';
const posix = path.posix;

const toPosix = p => p.split(path.sep).join('/');
const sha256 = data => createHash('sha256').update(data).digest('hex');
const escapeHtml = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const unescapeHtml = s => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#(39|x27);/g, "'").replace(/&amp;/g, '&');
const lf = s => s.replace(/\r\n?/g, '\n');

async function listFiles(dir, base = dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(full, base));
    else files.push(toPosix(path.relative(base, full)));
  }
  return files.sort();
}

async function readManifest(snapshot) {
  const file = path.join(snapshot, MANIFEST);
  return existsSync(file) ? JSON.parse(await readFile(file, 'utf8')) : null;
}

function describeChanges(before, after) {
  const changes = [];
  for (const file of Object.keys(after)) {
    if (!(file in before)) changes.push(`  added    ${file}`);
    else if (before[file] !== after[file]) changes.push(`  changed  ${file}`);
  }
  for (const file of Object.keys(before)) if (!(file in after)) changes.push(`  removed  ${file}`);
  return changes;
}

async function sourceHashes(source) {
  const hashes = {};
  for (const file of (await listFiles(source)).filter(f => !f.endsWith('.meta')))
    hashes[file] = sha256(await readFile(path.join(source, file)));
  return hashes;
}

// ---------------------------------------------------------------- import

async function importDocs(product, sourceArg) {
  const source = path.resolve(ROOT, sourceArg ?? product.source);
  if (!existsSync(source))
    throw new Error(`Source folder not found: ${source}\nPass --source <folder> or fix "source" in scripts/docs.config.json.`);
  const files = (await listFiles(source)).filter(f => !f.endsWith('.meta'));
  if (!files.some(f => /\.md$/i.test(f))) throw new Error(`No Markdown files in ${source}`);

  const snapshot = path.join(ROOT, product.snapshot);
  const previous = await readManifest(snapshot);
  await rm(snapshot, { recursive: true, force: true });
  for (const file of files) {
    const target = path.join(snapshot, file);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(path.join(source, file), target);
  }

  const hashes = await sourceHashes(snapshot);
  const changes = describeChanges(previous?.files ?? {}, hashes);
  const manifest = {
    source: toPosix(path.relative(ROOT, source)),
    importedAt: changes.length || !previous ? new Date().toISOString() : previous.importedAt,
    files: hashes,
  };
  await writeFile(path.join(snapshot, MANIFEST), JSON.stringify(manifest, null, 2) + '\n');
  console.log(`${product.name}: imported ${files.length} files from ${manifest.source}`);
  console.log(changes.length ? changes.join('\n') : '  no changes since the last import');
}

// ---------------------------------------------------------------- render

const pageName = file => {
  const base = posix.basename(file, posix.extname(file)).toLowerCase();
  return posix.join(posix.dirname(file), (base === 'readme' ? 'index' : base) + '.html');
};

// Links name the file (index.html included), so pages also work when opened straight from disk.
const hrefTo = (from, to) => posix.relative('/' + posix.dirname(from), '/' + to);

// github-slugger: lowercase, drop punctuation except "-" and "_", one "-" per space, -1/-2 for repeats.
function uniqueSlug(seen, text) {
  const base = text.toLowerCase().replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, '').replace(/ /g, '-');
  let slug = base;
  while (Object.hasOwn(seen, slug)) slug = `${base}-${++seen[base]}`;
  seen[slug] = 0;
  return slug;
}

function pngSize(file) {
  if (!existsSync(file)) return null;
  const b = readFileSync(file);
  return b.length > 24 && b.readUInt32BE(0) === 0x89504e47 ? { width: b.readUInt32BE(16), height: b.readUInt32BE(20) } : null;
}

// Adds lazy loading to every image, including raw HTML <img> tags, and a height so the layout doesn't jump.
function enhanceImages(html, file, snapshot) {
  return html.replace(/<img\b([^>]*?)\s*\/?>/g, (tag, attrs) => {
    const src = attrs.match(/\ssrc="([^"]*)"/)?.[1];
    if (src && !/\sheight=/.test(attrs) && !/^[a-z][\w+.-]*:/i.test(src)) {
      const size = pngSize(path.join(snapshot, posix.normalize(posix.join(posix.dirname(file), decodeURI(src)))));
      const width = Number(attrs.match(/\swidth="(\d+)"/)?.[1]);
      if (size) attrs += width ? ` height="${Math.round(width * size.height / size.width)}"` : ` width="${size.width}" height="${size.height}"`;
    }
    if (!/\sloading=/.test(attrs)) attrs += ' loading="lazy"';
    if (!/\sdecoding=/.test(attrs)) attrs += ' decoding="async"';
    return `<img${attrs}>`;
  });
}

function renderMarkdown(md, file, pageOf, snapshot) {
  const seen = {};
  let firstH1 = null;
  const resolve = href => posix.normalize(posix.join(posix.dirname(file), decodeURI(href)));
  const marked = new Marked({ gfm: true });
  marked.use({
    renderer: {
      heading({ tokens, depth }) {
        const text = unescapeHtml(this.parser.parseInline(tokens, this.parser.textRenderer)).trim();
        firstH1 ??= depth === 1 ? text : null;
        const id = uniqueSlug(seen, text);
        return `<div class="heading"><h${depth} id="${id}">${this.parser.parseInline(tokens)}</h${depth}>` +
          `<a class="heading-anchor" href="#${id}" aria-label="Link to section: ${escapeHtml(text)}">#</a></div>\n`;
      },
      code({ text, lang }) {
        const language = (lang || '').trim().split(/\s+/)[0];
        const code = text.replace(/\n$/, '') + '\n';
        const html = language && hljs.getLanguage(language) ? hljs.highlight(code, { language, ignoreIllegals: true }).value : escapeHtml(code);
        return `<pre tabindex="0"><code${language ? ` class="language-${escapeHtml(language)}"` : ''}>${html}</code></pre>\n`;
      },
      table(token) {
        return `<div class="table-wrap" tabindex="0" role="region" aria-label="Table">\n${Renderer.prototype.table.call(this, token)}</div>\n`;
      },
      link(token) {
        const m = token.href.match(/^([^:?#]+\.md)(#.*)?$/i);
        const target = m && pageOf.get(resolve(m[1]));
        const href = target ? hrefTo(pageOf.get(file), target) + (m[2] ?? '') : token.href;
        return Renderer.prototype.link.call(this, { ...token, href });
      },
    },
  });
  return { html: enhanceImages(marked.parse(md), file, snapshot), firstH1 };
}

async function readVersion(snapshot, file) {
  const text = await readFile(path.join(snapshot, file), 'utf8');
  const match = text.match(/^##\s+\[?v?(\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)\]?/m);
  if (!match) throw new Error(`No version heading (for example "## 1.0.0") found in ${file}`);
  return match[1];
}

function fillTemplate(values) {
  return TEMPLATE.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in values)) throw new Error(`Unknown template placeholder {{${key}}}`);
    return values[key];
  });
}

async function render(product) {
  const snapshot = path.join(ROOT, product.snapshot);
  if (!existsSync(path.join(snapshot, MANIFEST)))
    throw new Error(`No imported docs for ${product.slug}. Run: node scripts/docs.mjs import ${product.slug}`);

  const files = (await listFiles(snapshot)).filter(f => f !== MANIFEST);
  // Only top-level Markdown files are pages; Markdown in subfolders (maintainer notes) isn't published.
  const markdown = files.filter(f => /\.md$/i.test(f) && !f.includes('/'));
  const pageOf = new Map(markdown.map(f => [f, pageName(f)]));
  const configured = product.pages ?? [];
  const problems = configured.filter(p => !pageOf.has(p.file)).map(p => `${p.file} is listed in docs.config.json but wasn't imported`);
  const order = [...configured.map(p => p.file).filter(f => pageOf.has(f)), ...markdown.filter(f => !configured.some(p => p.file === f))];
  const version = await readVersion(snapshot, product.versionFrom ?? 'CHANGELOG.md');

  const pages = [];
  for (const file of order) {
    const md = lf(await readFile(path.join(snapshot, file), 'utf8'));
    const { html, firstH1 } = renderMarkdown(md, file, pageOf, snapshot);
    const title = configured.find(p => p.file === file)?.title ?? firstH1 ?? file;
    pages.push({ file, out: pageOf.get(file), md, html, title });
  }

  const outputs = new Map();
  for (const page of pages) {
    const pagePath = posix.join(product.output, page.out);
    const up = posix.relative('/' + posix.dirname(pagePath), '/');
    const nav = pages.map(p => `<li><a href="${hrefTo(page.out, p.out)}"${p === page ? ' aria-current="page"' : ''}>${escapeHtml(p.title)}</a></li>`).join('\n          ');
    outputs.set(page.out, fillTemplate({
      marker: `${MARKER} from ${product.snapshot}/${page.file}. Do not edit: change the Markdown in the Unity project, then import and build.`,
      title: escapeHtml(page.title),
      product: escapeHtml(product.name),
      version: escapeHtml(version),
      description: escapeHtml(`${page.title} for ${product.name} ${version}, a Unity toolkit by IndieWest.`),
      root: up ? up + '/' : '',
      productHref: hrefTo(pagePath, product.productPage),
      docsHref: hrefTo(page.out, 'index.html'),
      nav,
      content: page.html.trimEnd(),
    }));
    problems.push(...checkCode(page));
  }
  for (const file of files.filter(f => !/\.md$/i.test(f))) outputs.set(file, await readFile(path.join(snapshot, file)));

  problems.push(...checkLinks(outputs, product.output));
  return { outputs, problems, version, pages };
}

// ---------------------------------------------------------------- checks

// Fenced code blocks as written in the Markdown, with the fence's own indentation removed.
function fencedBlocks(md) {
  const blocks = [];
  let open = null;
  for (const line of md.split('\n')) {
    if (!open) {
      const m = line.match(/^( *)(`{3,}|~{3,})/);
      if (m) open = { indent: m[1].length, fence: m[2], lines: [] };
      continue;
    }
    const close = line.match(/^ *(`{3,}|~{3,})\s*$/);
    if (close && close[1][0] === open.fence[0] && close[1].length >= open.fence.length) {
      blocks.push(open.lines.join('\n'));
      open = null;
    } else {
      open.lines.push(line.slice(Math.min(open.indent, line.match(/^ */)[0].length)));
    }
  }
  return blocks;
}

function checkCode(page) {
  const expected = fencedBlocks(page.md);
  const actual = [...page.html.matchAll(/<pre tabindex="0"><code(?: class="[^"]*")?>([\s\S]*?)<\/code><\/pre>/g)]
    .map(m => unescapeHtml(m[1].replace(/<\/?span[^>]*>/g, '')).replace(/\n$/, ''));
  if (expected.length !== actual.length)
    return [`${page.file}: ${expected.length} fenced code blocks in the Markdown but ${actual.length} in the HTML`];
  const problems = [];
  expected.forEach((block, i) => {
    if (block === actual[i]) return;
    const a = block.split('\n'), b = actual[i].split('\n');
    const line = a.findIndex((l, n) => l !== b[n]);
    problems.push(`${page.file}: code block ${i + 1} differs from the Markdown at line ${line + 1} of the block`);
  });
  return problems;
}

function checkLinks(outputs, outputDir) {
  const problems = [];
  const idCache = new Map();
  const local = repoPath => {
    const rel = posix.relative(outputDir, repoPath);
    return rel.startsWith('..') ? null : rel;
  };
  const contentOf = repoPath => {
    const rel = local(repoPath);
    if (rel !== null && outputs.has(rel)) return String(outputs.get(rel));
    const file = path.join(ROOT, repoPath);
    return existsSync(file) && statSync(file).isFile() ? readFileSync(file, 'utf8') : null;
  };
  const idsOf = repoPath => {
    if (!idCache.has(repoPath))
      idCache.set(repoPath, new Set([...(contentOf(repoPath) ?? '').matchAll(/\s(?:id|name)="([^"]+)"/g)].map(m => m[1])));
    return idCache.get(repoPath);
  };
  const exists = repoPath => {
    const rel = local(repoPath);
    if (rel !== null && outputs.has(rel)) return true;
    const file = path.join(ROOT, repoPath);
    return existsSync(file) && statSync(file).isFile();
  };

  for (const [out, content] of outputs) {
    if (!out.endsWith('.html')) continue;
    const pagePath = posix.join(outputDir, out);
    for (const [, attr, value] of String(content).matchAll(/\s(href|src)="([^"]*)"/g)) {
      if (/^[a-z][\w+.-]*:/i.test(value) || value.startsWith('//')) continue;
      const hash = value.indexOf('#');
      const rawPath = hash < 0 ? value : value.slice(0, hash);
      const fragment = hash < 0 ? '' : decodeURIComponent(value.slice(hash + 1));
      let target = rawPath ? posix.normalize(posix.join(posix.dirname(pagePath), decodeURI(rawPath))) : pagePath;
      if (target.startsWith('..')) { problems.push(`${out}: ${attr}="${value}" points outside the site`); continue; }
      if (rawPath.endsWith('/') || rawPath === '.' || (!exists(target) && exists(posix.join(target, 'index.html'))))
        target = posix.join(target, 'index.html');
      if (!exists(target)) { problems.push(`${out}: ${attr}="${value}" not found`); continue; }
      if (fragment && target.endsWith('.html') && !idsOf(target).has(fragment))
        problems.push(`${out}: ${attr}="${value}" has no element with id "${fragment}"`);
    }
  }
  return problems;
}

function report(problems) {
  if (!problems.length) return;
  throw new Error(`${problems.length} problem(s):\n` + problems.map(p => '  ' + p).join('\n'));
}

// ---------------------------------------------------------------- build / check

async function build(product) {
  const { outputs, problems, version, pages } = await render(product);
  report(problems);

  const outputDir = path.join(ROOT, product.output);
  if (existsSync(outputDir)) {
    for (const file of await listFiles(outputDir))
      if (file.endsWith('.html') && !(await readFile(path.join(outputDir, file), 'utf8')).includes(MARKER))
        throw new Error(`Refusing to clear ${product.output}: ${file} wasn't generated by this script.`);
    await rm(outputDir, { recursive: true, force: true });
  }
  for (const [file, content] of outputs) {
    const target = path.join(outputDir, file);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
  }
  console.log(`${product.name} ${version}: built ${pages.length} pages and ${outputs.size - pages.length} other files into ${product.output}/`);
}

async function check(product) {
  const { outputs, problems, version } = await render(product);
  const outputDir = path.join(ROOT, product.output);
  const onDisk = existsSync(outputDir) ? await listFiles(outputDir) : [];
  for (const [file, content] of outputs) {
    const target = path.join(outputDir, file);
    if (!existsSync(target)) problems.push(`${file} is missing from ${product.output}/ (run build)`);
    else if (typeof content === 'string' ? lf(await readFile(target, 'utf8')) !== content : !content.equals(await readFile(target)))
      problems.push(`${file} is out of date (run build)`);
  }
  for (const file of onDisk) if (!outputs.has(file)) problems.push(`${product.output}/${file} is no longer generated (run build)`);

  const source = path.resolve(ROOT, product.source);
  if (existsSync(source)) {
    const drift = describeChanges((await readManifest(path.join(ROOT, product.snapshot))).files, await sourceHashes(source));
    if (drift.length) console.warn(`Warning: the Unity docs changed since the last import (run import, then build):\n${drift.join('\n')}`);
  }
  report(problems);
  console.log(`${product.name} ${version}: links, code blocks and generated output are all OK`);
}

// ---------------------------------------------------------------- main

const args = process.argv.slice(2);
const command = args.shift();
const sourceIndex = args.indexOf('--source');
const sourceArg = sourceIndex >= 0 ? args.splice(sourceIndex, 2)[1] : undefined;
const slug = args[0];
const products = slug ? CONFIG.products.filter(p => p.slug === slug) : CONFIG.products;

try {
  if (!['import', 'build', 'check'].includes(command)) throw new Error('Usage: node scripts/docs.mjs <import|build|check> [product] [--source <folder>]');
  if (!products.length) throw new Error(`Unknown product "${slug}". Products: ${CONFIG.products.map(p => p.slug).join(', ')}`);
  if (sourceArg && products.length > 1) throw new Error('--source needs a product name when several products are configured');
  for (const product of products) {
    if (command === 'import') await importDocs(product, sourceArg);
    else if (command === 'build') await build(product);
    else await check(product);
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
